import androidx.compose.ui.graphics.vector.PathParser
import io.github.davidru85.multiverse.core.designsystem.tokens.MultiverseComponentDimensions

/**
 * The app's icons (`DEC-103`): only the Material Symbols Rounded glyphs the navigation bar renders, as
 * vector path data committed here rather than a `material-icons-extended` dependency that is neither
 * pinned nor the Symbols family.
 *
 * The path data is the official glyphs', verbatim from `google/material-design-icons`
 * (`symbols/web/<name>/materialsymbolsrounded/<name>[_fill1]_24px.svg`, Apache-2.0), drawn through
 * Compose's own path parser (`TASK-130`): the earlier hand-drawn approximations, read by a parser of this
 * file's own, were not the glyphs Figma `117:887` draws. `TEST-UNIT-108` compares each with its SVG.
 *
 * Each glyph is the 24 dp Symbols grid, so it scales with the layout and tints with the navigation
 * bar's own colours. The filled (`FILL 1`) and outlined variants are separate vectors, which is what
 * lets the bar show a filled icon for the selected destination and an outlined one otherwise
 * (`UI_SPEC.md` §4.1).
 */
public object MultiverseIcons {
    public val Groups: ImageVector by lazy { symbol("Groups", GROUPS_FILL) }
    public val GroupsOutlined: ImageVector by lazy { symbol("GroupsOutlined", GROUPS) }
    public val PlayArrow: ImageVector by lazy { symbol("PlayArrow", PLAY_ARROW_FILL) }
    public val PlayArrowOutlined: ImageVector by lazy { symbol("PlayArrowOutlined", PLAY_ARROW) }
    public val Favorite: ImageVector by lazy { symbol("Favorite", FAVORITE_FILL) }
    public val FavoriteOutlined: ImageVector by lazy { symbol("FavoriteOutlined", FAVORITE) }
    public val Settings: ImageVector by lazy { symbol("Settings", SETTINGS_FILL) }
    public val SettingsOutlined: ImageVector by lazy { symbol("SettingsOutlined", SETTINGS) }

    /** The portal mark, the brand shape the splash and the empty states draw (`UI_SPEC.md` §6.1). */
    public val PortalMark: ImageVector by lazy { vector("PortalMark", PORTAL_MARK_PATH, viewport = 24f, offsetY = 0f) }

    /**
     * A Symbols glyph: the grid is `0 -960 960 960`, so the glyph sits above the origin and the group
     * moves it down into the viewport.
     */
    private fun symbol(
        name: String,
        pathData: String,
    ): ImageVector = vector(name, pathData, viewport = SYMBOL_GRID, offsetY = SYMBOL_GRID)

    private fun vector(
        name: String,
        pathData: String,
        viewport: Float,
        offsetY: Float,
    ): ImageVector =
        ImageVector
            .Builder(
                name = name,
                defaultWidth = MultiverseComponentDimensions.icon,
                defaultHeight = MultiverseComponentDimensions.icon,
                viewportWidth = viewport,
                viewportHeight = viewport,
            ).addGroup(translationY = offsetY)
            .addPath(pathData = PathParser().parsePathString(pathData).toNodes(), fill = SolidColor(Color.White))
            .clearGroup()
            .build()

    /** The Material Symbols design grid, in viewport units. */
    private const val SYMBOL_GRID = 960f
}

